import type { Role } from '../types';
type AppUser = { name: string; role: Role };

/** Text starting with = + - @ (or tab/CR) can execute as a formula when the file is opened in Excel.
 *  Prefix it with an apostrophe so it is always shown as plain text. Numbers are left alone. */
export function safeCell(v: unknown): string | number | undefined {
  if (v === null || v === undefined) return undefined;
  if (typeof v === 'number') return v;
  const s = String(v);
  return /^[=+\-@\t\r]/.test(s) ? `'${s}` : s;
}

export interface Column<T> { header: string; key: string; width?: number; money?: boolean; value: (r: T) => string | number | undefined }

const save = (blob: Blob, name: string) => {
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob); a.download = name; a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 2000);
};
const stamp = () => new Date().toISOString().slice(0, 16).replace(/[:T]/g, '-');
export const fileName = (base: string, ext: string) => `AnwarCement_${base.replace(/\s+/g, '_')}_${stamp()}.${ext}`;

export interface ExportMeta { title: string; period?: string; scope: string; summary?: [string, string | number][]; user: AppUser }

/** Professional Excel export: brand header block, summary, frozen + filtered header row, currency formatting. */
/** SR users receive PDF instead of Excel for every download. */
export const usesPdf = (u: AppUser | null) => u?.role === 'sr';
/** Button label for the main download format of this user. */
export const mainFormatLabel = (u: AppUser | null) => (usesPdf(u) ? 'PDF' : 'Excel');

export async function exportExcel<T>(rows: T[], cols: Column<T>[], meta: ExportMeta) {
  if (usesPdf(meta.user)) {
    const { exportPdf } = await import('./exportPdf');
    await exportPdf(rows, cols, meta, fileName(meta.title, 'pdf'));
    return;
  }
  const ExcelJS = (await import('exceljs')).default;
  const wb = new ExcelJS.Workbook();
  wb.creator = 'Anwar Cement Sheet · Carpenter Payment System';
  wb.created = new Date();
  const ws = wb.addWorksheet(meta.title.slice(0, 31), { views: [{ state: 'frozen', ySplit: 0 }] });
  const red = 'FFC8102E';
  const last = cols.length;

  ws.mergeCells(1, 1, 1, last);
  Object.assign(ws.getCell(1, 1), { value: 'ANWAR CEMENT SHEET' });
  ws.getCell(1, 1).font = { bold: true, size: 16, color: { argb: red } };
  ws.mergeCells(2, 1, 2, last);
  ws.getCell(2, 1).value = meta.title;
  ws.getCell(2, 1).font = { bold: true, size: 13 };
  const info: [string, string | number][] = [
    ['Payment period', meta.period ?? 'All periods'], ['Scope', meta.scope], ['Generated', new Date().toLocaleString('en-GB')],
    ['Generated by', `${meta.user.name} (${meta.user.role})`], ['Total records', rows.length], ...(meta.summary ?? []),
  ];
  info.forEach(([k, v], i) => {
    const r = ws.getRow(3 + i);
    r.getCell(1).value = k; r.getCell(1).font = { bold: true, color: { argb: 'FF777777' } };
    r.getCell(2).value = safeCell(v) ?? '';
    if (typeof v === 'number' && /amount/i.test(k)) r.getCell(2).numFmt = '"৳"#,##0';
  });
  const headerRow = 3 + info.length + 1;
  const hr = ws.getRow(headerRow);
  cols.forEach((c, i) => {
    const cell = hr.getCell(i + 1);
    cell.value = c.header;
    cell.font = { bold: true, color: { argb: 'FFFFFFFF' } };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: red } };
    cell.alignment = { vertical: 'middle', wrapText: true };
    ws.getColumn(i + 1).width = c.width ?? Math.max(12, c.header.length + 4);
  });
  hr.height = 22;
  rows.forEach((row, ri) => {
    const r = ws.getRow(headerRow + 1 + ri);
    cols.forEach((c, i) => {
      const cell = r.getCell(i + 1);
      cell.value = safeCell(c.value(row)) ?? '';
      if (c.money) cell.numFmt = '"৳"#,##0';
      if (ri % 2) cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF7F7F7' } };
    });
  });
  ws.autoFilter = { from: { row: headerRow, column: 1 }, to: { row: headerRow + rows.length, column: last } };
  ws.views = [{ state: 'frozen', ySplit: headerRow }];
  const buf = await wb.xlsx.writeBuffer();
  save(new Blob([buf], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' }), fileName(meta.title, 'xlsx'));
}

export function exportCsv<T>(rows: T[], cols: Column<T>[], meta: ExportMeta) {
  const esc = (v: unknown) => { const s = String(v ?? ''); return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s; };
  const csv = [cols.map((c) => esc(c.header)).join(','), ...rows.map((r) => cols.map((c) => esc(safeCell(c.value(r)))).join(','))].join('\n');
  save(new Blob(['﻿' + csv], { type: 'text/csv;charset=utf-8' }), fileName(meta.title, 'csv'));
}

